package eus.martico.fileTransfer.model.tabladetablas.vo;

public class TablaCabeceraVO {

	private Long ni;
	private String codigo;
	private String descEs;
	private String descEus;
	
	public Long getNi() {
		return ni;
	}
	public void setNi(Long ni) {
		this.ni = ni;
	}
	public String getCodigo() {
		return codigo;
	}
	public void setCodigo(String codigo) {
		this.codigo = codigo;
	}
	public String getDescEus() {
		return descEus;
	}
	public void setDescEus(String descEus) {
		this.descEus = descEus;
	}
	public String getDescEs() {
		return descEs;
	}
	public void setDescEs(String descEs) {
		this.descEs = descEs;
	}

}
